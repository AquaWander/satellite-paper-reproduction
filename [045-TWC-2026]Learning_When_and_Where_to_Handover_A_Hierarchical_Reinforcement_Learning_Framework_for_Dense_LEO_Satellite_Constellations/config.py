def compute_sinr_floor_db():
    """由 R_min@B 反推 SINR 门限（dB）。R = B·log2(1+SINR) ⇒ SINR = 2^(R/B) − 1。"""
    B = RF['bandwidth_Hz']
    R_min = RF['min_rate_Mbps'] * 1e6  # bps
    sinr_lin = 2.0 ** (R_min / B) - 1.0
    return 10.0 * np.log10(sinr_lin)


